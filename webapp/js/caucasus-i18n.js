// English text is already represented by a canonical I18N key.
(function buildCorePhraseAliases() {
  function walk(node, prefix = '') {
    if (!node || typeof node !== 'object' || Array.isArray(node)) return;
    if (typeof node.en === 'string') {
      for (const lang of ['ce','av']) {
        const value = CAUCASUS_I18N.keys[lang][prefix];
        if (value) CAUCASUS_I18N.phrases[lang][node.en] = value;
      }
    }
    for (const [key, value] of Object.entries(node)) {
      if (key === 'en' || !value || typeof value !== 'object' || Array.isArray(value)) continue;
      walk(value, prefix ? prefix + '.' + key : key);
    }
  }
  if (typeof I18N !== 'undefined') walk(I18N);
})();

